function demoLocation(name: string): ClipLocation {
  if (name.startsWith("2026-08-20_22")) {
    return { street: "七賢二路", lat: 22.6334, lon: 120.296 };
  }
  if (name.startsWith("2026-08-21_02")) {
    return { street: "沿海路", lat: 22.4645, lon: 120.462 };
  }
  if (name.startsWith("2026-08-21_14")) {
    return { street: "中華路", lat: 22.627, lon: 120.301 };
  }
  if (name.startsWith("2026-08-23_15")) {
    return { street: "成功路", lat: 22.62, lon: 120.312 };
  }
  if (name.startsWith("2026-08-25_23")) {
    return { street: "五福路", lat: 22.63, lon: 120.299 };
  }
  if (name.startsWith("2026-08-26_17")) {
    return { street: "民族路", lat: 22.64, lon: 120.31 };
  }
  return { street: "中山路", lat: 22.62, lon: 120.31 };
}

export function createDemoClips(): Clip[] {
  return DEMO_EVENTS.map(({ name, mb }) => {
    const timestamp = parseClipFolderName(name);
    if (!timestamp) {
      throw new Error(`Demo timestamp could not be parsed: ${name}`);
    }
    return {
      id: name,
      name,
      timestamp,
      size: Math.round(mb * 1024 * 1024),
      fileCount: 4,
      kind: "SentryClips" as const,
      location: demoLocation(name),
    };
  });
}
