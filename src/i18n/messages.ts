export const messages: Record<Locale, Messages> = {
  en,
  "zh-Hant": zhHant,
};

export function explain(error: unknown, copy: Messages, fallback: string): string {
  if (error instanceof CodedError) {
    return lookup(copy, error.message, error.detail) ?? fallback;
  }
  if (typeof error === "string") return lookup(copy, error, "") ?? error;
  if (error instanceof Error) {
    return lookup(copy, error.message, "") ?? (error.message || fallback);
  }
  return fallback;
}

function lookup(copy: Messages, code: string, detail: string): string | null {
  const table: Record<string, string | ((value: string) => string)> = copy.errors;
  const entry = table[code];
  if (typeof entry === "function") return entry(detail);
  if (typeof entry === "string") return entry;
  return null;
}
